class SinglesMatchSimulator:
    def __init__(self, player_a: SinglesPlayer, player_b: SinglesPlayer, context: MatchContext, best_of: int = 3):
        self.player_a = player_a
        self.player_b = player_b
        self.context = context
        self.best_of = best_of
        self.sets_to_win = best_of // 2 + 1
        self.p_a_serves = (player_a.serve_first_pct * player_a.serve_first_won_pct + 
                          (1 - player_a.serve_first_pct) * player_a.serve_second_won_pct)
        self.p_b_serves = (player_b.serve_first_pct * player_b.serve_first_won_pct + 
                          (1 - player_b.serve_first_pct) * player_b.serve_second_won_pct)
        
        # Fatigue scaling based on best of 3 vs 5
        if best_of == 5:
            self.kinetic_fatigue_rate = 0.004
            self.cns_fatigue_rate = 0.0005
        else:
            self.kinetic_fatigue_rate = 0.006
            self.cns_fatigue_rate = 0.0008
    
    def _apply_fatigue(self, p_base: float, player: SinglesPlayer, state: MatchState) -> float:
        kinetic_fatigue = state.total_phase4_points * self.kinetic_fatigue_rate * (1 - player.kinetic_endurance)
        cns_fatigue = state.total_points_played * self.cns_fatigue_rate * (1 - player.cns_endurance)
        total_fatigue = kinetic_fatigue + cns_fatigue
        p_adjusted = p_base * (1 - total_fatigue)
        return np.clip(p_adjusted, 0.30, 0.85)
    
    def _apply_momentum(self, p_base: float, player: SinglesPlayer, momentum: float, is_server: bool) -> float:
        if is_server:
            momentum_effect = momentum * 0.015 * player.momentum_sensitivity
        else:
            momentum_effect = -momentum * 0.015 * player.momentum_sensitivity
        p_adjusted = p_base + momentum_effect
        return np.clip(p_adjusted, 0.30, 0.85)
    
    def _apply_clutch(self, p_base: float, player: SinglesPlayer, is_break_point: bool) -> float:
        if is_break_point:
            p_adjusted = p_base * (2.0 - player.clutch_factor)
            return np.clip(p_adjusted, 0.30, 0.85)
        return p_base
    
    def _apply_volatility(self, p_base: float) -> float:
        variance_band = self.context.volatility_multiplier * 0.05
        noise = np.random.normal(0, variance_band)
        p_adjusted = p_base + noise
        return np.clip(p_adjusted, 0.20, 0.90)
    
    def _determine_rally_phase(self, server: SinglesPlayer) -> int:
        phases = [(1, server.phase1_win_pct), (2, server.phase2_win_pct), 
                  (3, server.phase3_win_pct), (4, server.phase4_win_pct)]
        total = sum(p for _, p in phases)
        if total == 0:
            return 3
        rand = np.random.random() * total
        cumulative = 0
        for phase, prob in phases:
            cumulative += prob
            if rand <= cumulative:
                return phase
        return 4
    
    def _simulate_point(self, server: SinglesPlayer, receiver: SinglesPlayer, 
                        state: MatchState, game_state: GameState) -> Tuple[bool, int]:
        p_base = self.p_a_serves if server == self.player_a else self.p_b_serves
        is_break_point = game_state.is_break_point()
        p = p_base
        p = self._apply_fatigue(p, server, state)
        p = self._apply_momentum(p, server, state.momentum, is_server=True)
        p = self._apply_clutch(p, server, is_break_point)
        p = self._apply_volatility(p)
        phase = self._determine_rally_phase(server)
        if phase == 4:
            p *= 0.95
            p = np.clip(p, 0.30, 0.85)
        server_wins = np.random.random() < p
        return server_wins, phase
    
    def _simulate_game(self, server: SinglesPlayer, receiver: SinglesPlayer, 
                       state: MatchState) -> Tuple[bool, int, int]:
        game_state = GameState()
        points_in_game = 0
        phase4_in_game = 0
        while True:
            server_wins, phase = self._simulate_point(server, receiver, state, game_state)
            points_in_game += 1
            state.total_points_played += 1
            if phase == 4:
                phase4_in_game += 1
                state.total_phase4_points += 1
            if server_wins:
                game_state.server_points += 1
            else:
                game_state.receiver_points += 1
            is_over, server_won = game_state.is_game_over()
            if is_over:
                if server_won:
                    state.momentum += 0.5
                else:
                    state.momentum -= 0.5
                state.momentum = np.clip(state.momentum, -5, 5)
                return server_won, points_in_game, phase4_in_game
    
    def _simulate_tiebreak(self, server_a_first: bool, state: MatchState, 
                           target_points: int = 7) -> Tuple[bool, int, int]:
        a_points = 0
        b_points = 0
        tb_points = 0
        tb_phase4 = 0
        while True:
            total_points = a_points + b_points
            
            if total_points == 0:
                server = self.player_a if server_a_first else self.player_b
            else:
                server_block = (total_points + 1) // 2
                if server_block % 2 == 0:
                    server = self.player_a if server_a_first else self.player_b
                else:
                    server = self.player_b if server_a_first else self.player_a
            
            receiver = self.player_b if server == self.player_a else self.player_a
            empty_game_state = GameState()
            server_wins, phase = self._simulate_point(server, receiver, state, empty_game_state)
            tb_points += 1
            state.total_points_played += 1
            if phase == 4:
                tb_phase4 += 1
                state.total_phase4_points += 1
            if server_wins:
                if server == self.player_a:
                    a_points += 1
                else:
                    b_points += 1
            else:
                if server == self.player_a:
                    b_points += 1
                else:
                    a_points += 1
            if a_points >= target_points and a_points - b_points >= 2:
                return True, tb_points, tb_phase4
            if b_points >= target_points and b_points - a_points >= 2:
                return False, tb_points, tb_phase4
    
    def _simulate_set(self, starting_server: SinglesPlayer, 
                      state: MatchState) -> Tuple[bool, int, int, int, int, bool]:
        set_state = SetState()
        points_in_set = 0
        phase4_in_set = 0
        current_server = starting_server
        while True:
            server_wins, points_in_game, phase4_in_game = self._simulate_game(
                current_server,
                self.player_b if current_server == self.player_a else self.player_a,
                state
            )
            points_in_set += points_in_game
            phase4_in_set += phase4_in_game
            if server_wins:
                if current_server == self.player_a:
                    set_state.games_server += 1
                else:
                    set_state.games_receiver += 1
            else:
                if current_server == self.player_a:
                    set_state.games_receiver += 1
                else:
                    set_state.games_server += 1
            current_server = self.player_b if current_server == self.player_a else self.player_a
            is_over, server_won = set_state.is_set_over()
            if is_over:
                games_a = set_state.games_server
                games_b = set_state.games_receiver
                if server_won:
                    return True, games_a, games_b, points_in_set, phase4_in_set, False
                else:
                    return False, games_a, games_b, points_in_set, phase4_in_set, False
            if set_state.is_tiebreak():
                a_wins_tb, tb_points, tb_phase4 = self._simulate_tiebreak(
                    current_server == self.player_a, state, target_points=7
                )
                points_in_set += tb_points
                phase4_in_set += tb_phase4
                if a_wins_tb:
                    return True, 7, 6, points_in_set, phase4_in_set, True
                else:
                    return False, 6, 7, points_in_set, phase4_in_set, True
    
    def simulate_match(self) -> Dict:
        state = MatchState()
        set_scores = []
        tiebreaks = 0
        total_games_a = 0
        total_games_b = 0
        starting_server = self.player_a
        while True:
            is_over, a_won = state.is_match_over(self.sets_to_win)
            if is_over:
                break
            a_wins_set, games_a, games_b, points_in_set, phase4_in_set, had_tb = self._simulate_set(
                starting_server, state
            )
            if a_wins_set:
                state.sets_server += 1
            else:
                state.sets_receiver += 1
            total_games_a += games_a
            total_games_b += games_b
            set_scores.append((games_a, games_b))
            if had_tb:
                tiebreaks += 1
            state.current_set_number += 1
            starting_server = self.player_b if starting_server == self.player_a else self.player_a
        return {{
            "winner": "A" if state.sets_server > state.sets_receiver else "B",
            "sets_a": state.sets_server, "sets_b": state.sets_receiver,
            "games_a": total_games_a, "games_b": total_games_b,
            "total_games": total_games_a + total_games_b,
            "game_margin": total_games_a - total_games_b,
            "set_scores": set_scores, "tiebreaks": tiebreaks,
            "total_points": state.total_points_played,
            "phase4_points": state.total_phase4_points,
            "num_sets": state.sets_server + state.sets_receiver,
        }}

