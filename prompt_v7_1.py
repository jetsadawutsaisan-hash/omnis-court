@dataclass
class GameState:
    server_points: int = 0
    receiver_points: int = 0
    
    def is_game_over(self) -> Tuple[bool, bool]:
        if self.server_points >= 4 and self.server_points - self.receiver_points >= 2:
            return True, True
        if self.receiver_points >= 4 and self.receiver_points - self.server_points >= 2:
            return True, False
        return False, False
    
    def is_break_point(self) -> bool:
        return self.receiver_points >= 3 and self.server_points < self.receiver_points

@dataclass
class SetState:
    games_server: int = 0
    games_receiver: int = 0
    
    def is_set_over(self) -> Tuple[bool, bool]:
        if self.games_server >= 6 and self.games_server - self.games_receiver >= 2:
            return True, True
        if self.games_receiver >= 6 and self.games_receiver - self.games_server >= 2:
            return True, False
        return False, False
    
    def is_tiebreak(self) -> bool:
        return self.games_server == 6 and self.games_receiver == 6

@dataclass
class MatchState:
    sets_server: int = 0
    sets_receiver: int = 0
    current_set_number: int = 1
    total_points_played: int = 0
    total_phase4_points: int = 0
    momentum: float = 0.0
    
    def is_match_over(self, sets_to_win: int) -> Tuple[bool, bool]:
        if self.sets_server >= sets_to_win:
            return True, True
        if self.sets_receiver >= sets_to_win:
            return True, False
        return False, False

