class DoublesMatchSimulator:
    def __init__(self, team_a: DoublesTeam, team_b: DoublesTeam, 
                 context: MatchContext, best_of: int = 3):
        self.team_a = team_a
        self.team_b = team_b
        self.context = context
        self.best_of = best_of
        self.sets_to_win = best_of // 2 + 1
        self.uses_super_tiebreak = context.uses_super_tiebreak
        
        self.p_a_serves = team_a.team_serve_hold_pct
        self.p_b_serves = team_b.team_serve_hold_pct
    
    def _apply_fatigue(self, p_base: float, team: DoublesTeam, state: MatchState) -> float:
        kinetic_fatigue = state.total_phase4_points * 0.004 * (1 - team.partnership_chemistry * 0.5)
        cns_fatigue = state.total_points_played * 0.0005 * (1 - team.communication_quality * 0.3)
        total_fatigue = kinetic_fatigue + cns_fatigue
        p_adjusted = p_base * (1 - total_fatigue)
        return np.clip(p_adjusted, 0.35, 0.88)
    
    def _apply_momentum(self, p_base: float, team: DoublesTeam, momentum: float, is_server: bool) -> float:
        if is_server:
            momentum_effect = momentum * 0.012 * team.partnership_chemistry
        else:
            momentum_effect = -momentum * 0.012 * team.partnership_chemistry
        p_adjusted = p_base + momentum_effect
        return np.clip(p_adjusted, 0.35, 0.88)
    
    def _apply_clutch(self, p_base: float, team: DoublesTeam, is_break_point: bool) -> float:
        if is_break_point:
            clutch_modifier = 1.0 + (team.partnership_chemistry - 0.5) * 0.2
            p_adjusted = p_base * clutch_modifier
            return np.clip(p_adjusted, 0.35, 0.88)
        return p_base
    
    def _apply_volatility(self, p_base: float) -> float:
        variance_band = self.context.volatility_multiplier * 0.04
        noise = np.random.normal(0, variance_band)
        p_adjusted = p_base + noise
        return np.clip(p_adjusted, 0.25, 0.90)
    
    def _apply_net_dominance(self, p_base: float, server_team: DoublesTeam, 
                              receiver_team: DoublesTeam) -> float:
        server_net_advantage = server_team.net_aggression_factor - receiver_team.net_aggression_factor
        net_modifier = 1.0 + server_net_advantage * 0.15
        p_adjusted = p_base * net_modifier
        return np.clip(p_adjusted, 0.35, 0.88)
    
    def _determine_rally_phase(self, server_team: DoublesTeam) -> int:
        phase1_adj = server_team.net_aggression_factor * 0.1
        phases = [
            (1, 0.40 + phase1_adj),
            (2, 0.30),
            (3, 0.20),
            (4, 0.10)
        ]
        total = sum(p for _, p in phases)
        rand = np.random.random() * total
        cumulative = 0
        for phase, prob in phases:
            cumulative += prob
            if rand <= cumulative:
                return phase
        return 2
    
    def _simulate_point(self, server_team: DoublesTeam, receiver_team: DoublesTeam,
                        state: MatchState, game_state: GameState) -> Tuple[bool, int]:
        p_base = self.p_a_serves if server_team == self.team_a else self.p_b_serves
        is_break_point = game_state.is_break_point()
        p = p_base
        p = self._apply_fatigue(p, server_team, state)
        p = self._apply_momentum(p, server_team, state.momentum, is_server=True)
        p = self._apply_clutch(p, server_team, is_break_point)
        p = self._apply_net_dominance(p, server_team, receiver_team)
        p = self._apply_volatility(p)
        phase = self._determine_rally_phase(server_team)
        if phase == 4:
            chemistry_diff = receiver_team.partnership_chemistry - server_team.partnership_chemistry
            p *= (1 - chemistry_diff * 0.1)
            p = np.clip(p, 0.35, 0.88)
        server_wins = np.random.random() < p
        return server_wins, phase
    
    def _simulate_game(self, server_team: DoublesTeam, receiver_team: DoublesTeam,
                       state: MatchState) -> Tuple[bool, int, int]:
        game_state = GameState()
        points_in_game = 0
        phase4_in_game = 0
        while True:
            server_wins, phase = self._simulate_point(
                server_team, receiver_team, state, game_state
            )
            points_in_game += 1
            state.total_points_played += 1
            if phase == 4:
                phase4_in_game += 1
                state.total_phase4_points += 1
            if server_wins:
                game_state.server_points += 1
            else:
                game_state.receiver_points += 1
            is_over, server_won = game_state.is_game_over()
            if is_over:
                if server_won:
                    state.momentum += 0.4
                else:
                    state.momentum -= 0.4
                state.momentum = np.clip(state.momentum, -4, 4)
                return server_won, points_in_game, phase4_in_game
    
    def _simulate_tiebreak(self, server_a_first: bool, state: MatchState,
                           target_points: int = 7) -> Tuple[bool, int, int]:
        a_points = 0
        b_points = 0
        tb_points = 0
        tb_phase4 = 0
        while True:
            total_points = a_points + b_points
            
            if total_points == 0:
                server_team = self.team_a if server_a_first else self.team_b
            else:
                server_block = (total_points + 1) // 2
                if server_block % 2 == 0:
                    server_team = self.team_a if server_a_first else self.team_b
                else:
                    server_team = self.team_b if server_a_first else self.team_a
            
            receiver_team = self.team_b if server_team == self.team_a else self.team_a
            empty_game_state = GameState()
            server_wins, phase = self._simulate_point(
                server_team, receiver_team, state, empty_game_state
            )
            tb_points += 1
            state.total_points_played += 1
            if phase == 4:
                tb_phase4 += 1
                state.total_phase4_points += 1
            if server_wins:
                if server_team == self.team_a:
                    a_points += 1
                else:
                    b_points += 1
            else:
                if server_team == self.team_a:
                    b_points += 1
                else:
                    a_points += 1
            if a_points >= target_points and a_points - b_points >= 2:
                return True, tb_points, tb_phase4
            if b_points >= target_points and b_points - a_points >= 2:
                return False, tb_points, tb_phase4
    
    def _simulate_set(self, starting_server_team: DoublesTeam,
                      state: MatchState, is_final_set_with_super_tb: bool = False) -> Tuple[bool, int, int, int, int, bool]:
        set_state = SetState()
        points_in_set = 0
        phase4_in_set = 0
        current_server_team = starting_server_team
        while True:
            server_wins, points_in_game, phase4_in_game = self._simulate_game(
                current_server_team,
                self.team_b if current_server_team == self.team_a else self.team_a,
                state
            )
            points_in_set += points_in_game
            phase4_in_set += phase4_in_game
            if server_wins:
                if current_server_team == self.team_a:
                    set_state.games_server += 1
                else:
                    set_state.games_receiver += 1
            else:
                if current_server_team == self.team_a:
                    set_state.games_receiver += 1
                else:
                    set_state.games_server += 1
            current_server_team = self.team_b if current_server_team == self.team_a else self.team_a
            is_over, server_won = set_state.is_set_over()
            if is_over:
                games_a = set_state.games_server
                games_b = set_state.games_receiver
                if server_won:
                    return True, games_a, games_b, points_in_set, phase4_in_set, False
                else:
                    return False, games_a, games_b, points_in_set, phase4_in_set, False
            if set_state.is_tiebreak():
                if is_final_set_with_super_tb:
                    a_wins_tb, tb_points, tb_phase4 = self._simulate_tiebreak(
                        current_server_team == self.team_a, state, target_points=10
                    )
                else:
                    a_wins_tb, tb_points, tb_phase4 = self._simulate_tiebreak(
                        current_server_team == self.team_a, state, target_points=7
                    )
                points_in_set += tb_points
                phase4_in_set += tb_phase4
                if a_wins_tb:
                    return True, 7, 6, points_in_set, phase4_in_set, True
                else:
                    return False, 6, 7, points_in_set, phase4_in_set, True
    
    def simulate_match(self) -> Dict:
        state = MatchState()
        set_scores = []
        tiebreaks = 0
        total_games_a = 0
        total_games_b = 0
        starting_server_team = self.team_a
        while True:
            is_over, a_won = state.is_match_over(self.sets_to_win)
            if is_over:
                break
            is_final_set = (state.sets_server == self.sets_to_win - 1 and 
                           state.sets_receiver == self.sets_to_win - 1)
            use_super_tb = self.uses_super_tiebreak and is_final_set
            
            a_wins_set, games_a, games_b, points_in_set, phase4_in_set, had_tb = self._simulate_set(
                starting_server_team, state, is_final_set_with_super_tb=use_super_tb
            )
            if a_wins_set:
                state.sets_server += 1
            else:
                state.sets_receiver += 1
            total_games_a += games_a
            total_games_b += games_b
            set_scores.append((games_a, games_b))
            if had_tb:
                tiebreaks += 1
            state.current_set_number += 1
            starting_server_team = self.team_b if starting_server_team == self.team_a else self.team_a
        return {{
            "winner": "A" if state.sets_server > state.sets_receiver else "B",
            "sets_a": state.sets_server, "sets_b": state.sets_receiver,
            "games_a": total_games_a, "games_b": total_games_b,
            "total_games": total_games_a + total_games_b,
            "game_margin": total_games_a - total_games_b,
            "set_scores": set_scores, "tiebreaks": tiebreaks,
            "total_points": state.total_points_played,
            "phase4_points": state.total_phase4_points,
            "num_sets": state.sets_server + state.sets_receiver,
            "match_type": "doubles",
        }}

